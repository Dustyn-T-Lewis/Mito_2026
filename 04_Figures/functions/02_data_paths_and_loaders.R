# Input paths, data loaders, and the old-combined-results -> brief contrast
# naming map. Reads existing 01-03 pipeline outputs only; never re-runs them.

source(here::here("04_Figures", "functions", "01_style_palettes_theme.R"))

# Brief contrast naming
# The limma model is already fit; 03_combined_results.csv carries 5 contrasts
# under the OLD names. Map them to the brief's names for display; algebra identical.
CONTRAST_DISPLAY_MAP <- c(
  CTLvMITO      = "Transplant", # Mito - Ctl
  CTLvPHE       = "Disease", # PHE - Ctl
  PHEvPHE_MITO  = "Rescue", # PHE_Mito - PHE
  Interaction   = "Interaction", # orthogonal 2x2
  MITOvPHE_MITO = "Secondary" # PHE_Mito - Mito
)

# Verbatim math labels (Unicode minus U+2212) keyed by OLD name, built from the
# condition display labels so a relabel flows through here automatically.
CONTRAST_MATH_BRIEF <- local({
  g <- H9C2_GROUP_LABELS
  c(
    CTLvMITO = sprintf("%s − %s", g[["Mito"]], g[["Ctl"]]),
    CTLvPHE = sprintf("%s − %s", g[["PHE"]], g[["Ctl"]]),
    PHEvPHE_MITO = sprintf("%s − %s", g[["PHE_Mito"]], g[["PHE"]]),
    Interaction = sprintf(
      "(%s − %s) − (%s − %s)",
      g[["PHE_Mito"]], g[["Mito"]], g[["PHE"]], g[["Ctl"]]
    ),
    MITOvPHE_MITO = sprintf("%s − %s", g[["PHE_Mito"]], g[["Mito"]])
  )
})

# Short brief display name for tight strips.
contrast_brief <- function(old_name) {
  out <- CONTRAST_DISPLAY_MAP[old_name]
  ifelse(is.na(out), old_name, unname(out))
}

